// @vitest-environment node
import { readdirSync, readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

// Regression: an unanchored "supabase" pattern also matched src/lib/supabase/,
// so Vercel deployments were missing the Supabase clients and the build failed.
const patterns = readFileSync(".vercelignore", "utf8")
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line !== "" && !line.startsWith("#"));

describe(".vercelignore", () => {
  it("anchors every pattern to the repository root", () => {
    const unanchored = patterns.filter((pattern) => !pattern.replace(/^!/, "").startsWith("/"));
    expect(unanchored).toEqual([]);
  });

  it("never excludes the app's source or public files", () => {
    const touchesApp = patterns.filter((pattern) => /^!?\/(src|public)(\/|$)/.test(pattern));
    expect(touchesApp).toEqual([]);
  });

  it("keeps local secrets and the Supabase folder out of uploads", () => {
    expect(patterns).toContain("/.env*");
    expect(patterns).toContain("!/.env.example");
    expect(patterns).toContain("/supabase/");
  });

  // Regression (M9 staging build): playwright.config.ts imported tests/e2e/support/,
  // which isn't uploaded, and Next's type check of every .ts file failed.
  it("leaves no uploaded root config importing an excluded folder", () => {
    // .next/ is excluded from uploads but regenerated by the build itself.
    const excluded = patterns
      .filter((pattern) => pattern.endsWith("/") && !pattern.startsWith("!") && pattern !== "/.next/")
      .map((pattern) => pattern.slice(1));
    const uploaded = readdirSync(".").filter(
      (file) => /\.(ts|mts|tsx)$/.test(file) && !patterns.includes(`/${file}`),
    );
    const offenders = uploaded.filter((file) => {
      // Every module specifier in `import … from "x"` and `import "x"`.
      const specifiers = [...readFileSync(file, "utf8").matchAll(/^\s*import\s[^;]*?["']([^"']+)["']/gm)].map((m) => m[1] ?? "");
      return specifiers.some((specifier) => excluded.some((folder) => specifier.startsWith(`./${folder}`)));
    });
    expect(uploaded).toContain("next.config.ts");
    expect(offenders).toEqual([]);
  });
});
